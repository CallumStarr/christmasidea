import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { securityHeaders } from "../src/security-headers.js";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const SITE = join(ROOT, "site");
const OUTPUT = join(ROOT, "src", "csp-hashes.js");
// Data blocks (JSON-LD) are never executed, so script-src does not govern them.
const DATA_TYPES = /^(?:application\/(?:ld\+)?json|text\/plain)$/i;

/** CSP source expressions for every executable inline script, hashed as browsers do (after newline normalisation). */
export function inlineScriptHashes(html) {
  const hashes = [];
  for (const match of String(html).matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    const attributes = match[1];
    if (/\bsrc\s*=/i.test(attributes)) continue;
    const type = /\btype\s*=\s*["']?([^"'\s>]+)/i.exec(attributes)?.[1] || "";
    if (DATA_TYPES.test(type)) continue;
    const text = match[2].replace(/\r\n?/g, "\n");
    hashes.push(`'sha256-${createHash("sha256").update(text, "utf8").digest("base64")}'`);
  }
  return hashes;
}

export function siteInlineScriptHashes(site = SITE) {
  const files = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (entry.name.endsWith(".html")) files.push(path);
    }
  };
  walk(site);
  const sources = new Map();
  for (const file of files.sort()) {
    for (const hash of inlineScriptHashes(readFileSync(file, "utf8"))) {
      if (!sources.has(hash)) sources.set(hash, []);
      sources.get(hash).push(relative(site, file).replaceAll("\\", "/"));
    }
  }
  return [...sources].sort(([a], [b]) => a.localeCompare(b));
}

export function renderHashModule(entries) {
  return [
    "// Generated by scripts/build-csp-hashes.mjs (run by `npm run build:pages`). Do not edit by hand.",
    "export const INLINE_SCRIPT_HASHES = [",
    ...entries.map(([hash, files]) => `  "${hash}", // ${files.join(", ")}`),
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const entries = siteInlineScriptHashes();
  writeFileSync(OUTPUT, renderHashModule(entries));
  writeFileSync(join(SITE, "_headers"), "# Generated by scripts/build-csp-hashes.mjs. Do not edit by hand.\n/*\n"
    + Object.entries(securityHeaders(entries.map(([hash]) => hash)))
      .map(([name, value]) => `  ${name}: ${value}`).join("\n") + "\n");
  console.log(`Wrote ${entries.length} inline script hashes to ${relative(ROOT, OUTPUT)}.`);
}
